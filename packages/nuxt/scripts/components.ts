// Writes `src/components.ts`: every component and public composable the
// packages' entries export, so the module registers them without loading any
// package code. `npm run build` runs it; a test checks the file is current.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const packages = fileURLToPath(new URL('../../', import.meta.url));

/** An entry, and the optional peers an app must have for it to be registered. */
const ENTRIES = [
  { from: '@vunset/vue', file: 'vue/src/index.ts', peers: [] },
  { from: '@vunset/vue/chart', file: 'vue/src/chart.ts', peers: ['@tanstack/charts'] },
  { from: '@vunset/vue/data-table', file: 'vue/src/data-table.ts', peers: ['@tanstack/vue-table'] },
  { from: '@vunset/ui', file: 'ui/src/index.ts', peers: [] },
  { from: '@vunset/ui/chart', file: 'ui/src/chart.ts', peers: ['@tanstack/charts'] },
  { from: '@vunset/ui/data-table', file: 'ui/src/data-table.ts', peers: ['@tanstack/vue-table'] }
];

// Components not exported as a `.vue` file's default.
const NAMED_COMPONENTS = new Set(['Part']);

const EXPORT_RE = /export\s*\{([^}]*)\}\s*from\s*'([^']+)'/g;

function exportsOf(file: string) {
  const source = readFileSync(packages + file, 'utf8');
  const components: string[] = [];
  const composables: string[] = [];
  for (const [, list, from] of source.matchAll(EXPORT_RE)) {
    for (const raw of list!.split(',')) {
      const specifier = raw.trim();
      if (!specifier || specifier.startsWith('type ')) continue;
      const name = specifier.split(/\s+as\s+/).pop()!;
      if (specifier.startsWith('default as ') && from!.endsWith('.vue')) components.push(name);
      else if (NAMED_COMPONENTS.has(name)) components.push(name);
      else if (/^use[A-Z]/.test(name)) composables.push(name);
    }
  }
  return { components, composables };
}

export function collect() {
  const entries = ENTRIES.map(({ from, file, peers }) => {
    const { components, composables } = exportsOf(file);
    return { from, peers, components, composables };
  });
  return entries.filter((entry) => entry.components.length > 0 || entry.composables.length > 0);
}

const UTIL_RE = /^export (?:async )?(?:function|const) (\w+)/gm;

/** Every value `@vunset/utils` exports, read from its source files. */
export function collectUtils() {
  const folder = 'utils/src/';
  return readdirSync(packages + folder)
    .filter((file) => file.endsWith('.ts') && file !== 'index.ts')
    .sort()
    .flatMap((file) => [...readFileSync(packages + folder + file, 'utf8').matchAll(UTIL_RE)].map((match) => match[1]!));
}

export function render() {
  const entries = collect().map(
    (entry) => `  {
    from: '${entry.from}',
    package: '${entry.from.split('/').slice(0, 2).join('/')}',
    peers: ${JSON.stringify(entry.peers).replaceAll('"', "'")},
    components: [${entry.components.map((name) => `'${name}'`).join(', ')}],
    composables: [${entry.composables.map((name) => `'${name}'`).join(', ')}]
  }`
  );
  return `// Generated by \`scripts/components.ts\` from the packages' entries. Don't edit.
export interface Entry {
  /** What the components are imported from. */
  from: string;
  /** The package it belongs to. */
  package: string;
  /** Optional peers the entry imports: without them installed, it is skipped. */
  peers: string[];
  components: string[];
  composables: string[];
}

export const ENTRIES: Entry[] = [
${entries.join(',\n')}
];

/** \`@vunset/utils\`' helpers, imported in the app and on the server. */
export const UTILS: string[] = [${collectUtils().map((name) => `'${name}'`).join(', ')}];
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL('../src/components.ts', import.meta.url), render());
}
